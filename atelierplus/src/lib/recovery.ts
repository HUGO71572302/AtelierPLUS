import { createHash, randomBytes, randomInt, timingSafeEqual } from "node:crypto";

// Same readable alphabet as invitation codes: no 0/O, 1/I/L.
const ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";

/** Validity of the 6-digit code given by the patron. */
export const PATRON_CODE_TTL_MINUTES = 30;
/** Wrong attempts allowed on a 6-digit code before it is burnt. */
export const MAX_PATRON_ATTEMPTS = 5;

/** Long recovery code kept by each user, e.g. K7QF-M2XR-9TBD. Shown once. */
export function generateRecoveryCode(): string {
  const bytes = randomBytes(12);
  let raw = "";
  for (const byte of bytes) raw += ALPHABET[byte % ALPHABET.length];
  return `${raw.slice(0, 4)}-${raw.slice(4, 8)}-${raw.slice(8, 12)}`;
}

/** Short code generated by the patron for a member who forgot the password. */
export function generatePatronCode(): string {
  return String(randomInt(0, 1_000_000)).padStart(6, "0");
}

export function normalizeCode(value: string): string {
  return value.toUpperCase().replace(/[^A-Z0-9]/g, "");
}

/** Codes are never stored in clear: only their SHA-256 hash is kept. */
export function hashCode(value: string): string {
  return createHash("sha256").update(normalizeCode(value)).digest("hex");
}

export function codesMatch(candidateHash: string, storedHash: string): boolean {
  const candidate = Buffer.from(candidateHash, "hex");
  const stored = Buffer.from(storedHash, "hex");
  return candidate.length === stored.length && timingSafeEqual(candidate, stored);
}
